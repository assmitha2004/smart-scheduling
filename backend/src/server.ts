import 'dotenv/config';
import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import rateLimit from 'express-rate-limit';
import { prisma } from './db';
import { requireAuth } from './middleware/auth';
import auth from './routes/auth';
import projects from './routes/projects';
import tasks from './routes/tasks';
import schedules from './routes/schedules';
const app=express();
app.use(helmet()); app.use(cors({origin:true})); app.use(express.json({limit:'1mb'}));
app.use(rateLimit({windowMs:15*60*1000,max:300,standardHeaders:true,legacyHeaders:false}));
app.get('/health',(_req,res)=>res.json({status:'ok',service:'smart-scheduling-api'}));
app.use('/api/v1/auth',auth); app.use('/api/v1/projects',requireAuth,projects); app.use('/api/v1/tasks',requireAuth,tasks); app.use('/api/v1/schedules',requireAuth,schedules);
app.get('/api/v1/briefings/daily',requireAuth,async(req:any,res)=>{const tasks=await prisma.task.findMany({where:{userId:req.userId,status:{not:'DONE'}},orderBy:[{dueAt:'asc'},{priority:'asc'}],take:8});res.json({date:new Date().toISOString(),headline:`You have ${tasks.length} active priorities to review.`,priorities:tasks.map(t=>({id:t.id,title:t.title,dueAt:t.dueAt,priority:t.priority,estimateMinutes:t.estimatedMinutes}))});});
const port=Number(process.env.PORT||4000); app.listen(port,()=>console.log(`Smart Scheduling API listening on ${port}`));
process.on('SIGINT',async()=>{await prisma.$disconnect();process.exit(0);});
